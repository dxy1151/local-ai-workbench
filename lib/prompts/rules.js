// 系统提示词里的「要求」段
//
// ⚠ 三条铁律，改之前先读：
//   1. 同一件事（字数、动作、环境）只能写一处。重复写必然互相打架 ——
//      已经踩过：customRules 说 250~350 字、hint 说 90 字、limitBlock 另一个上限，
//      模型只能随机挑一条，表现为「有时候短得离谱、有时候长得没边」。
//   2. **字数只由 limitBlock 给**（prompts/blocks.js），这里一律不写数字。
//   3. 可复用的句子片段在 shared.js，别在这里再手写一遍。
//
// 2026-11-22 重写：**只留扮演要求，把限制全撤了**。
//   之前的版本堆了「动作块不超过 15 字」「不写表情/感受/环境」「要克制、不要每句都加」
//   「空动作不许写」「一轮只推进一件事，说完就住口」—— 这些叠在一起的净效果是
//   **模型不敢写描写了**：动作变成一根干巴巴的短句，环境干脆不写，整条回复只剩台词。
//   用户的原话是「详细描写又没了」。
//
//   所以这一版的原则反过来：**只规定"你是谁、你写谁"，不规定"写多少"**。
//   篇幅交给 limitBlock，具体写多细交给场面本身。
//   留着的只有不管哪个模型都必须守的几条：人称、不替对方、不出戏。

import { TIME_ADVANCE_RULE, NO_SPEAK_FOR_USER_RULE } from './shared.js';

/** 人称铁律（本地写一份，不带"见别的条目"这类交叉引用 —— 那些条目已经被删了）。 */
const PERSON_RULE = '**你就是这个角色本人**：动作、神态、台词一律用「我」，对方一律是「你」。'
  + '不用「您」，不写角色名字当主语，不用"他/她"指代自己或对方，不写第三人称旁白。';

/* ---------- 精简版（compactSystem=true，给 27B 以下的模型）---------- */
//
// 只留最关键的几条，**全部是正向要求或边界，没有一条在压篇幅**。
//
// 顺序有讲究：把「你是本人」和「不替对方」放最前（这两条错得最明显），
// 再给"要写具体"这条正向引导 —— 它是这一版的重点。

export function compactRules() {
  return [
    '要求：',
    `- ${PERSON_RULE}`,
    '- ' + NO_SPEAK_FOR_USER_RULE,
    '- **直接点题**：对方说了什么，你就正面回应**那件事** —— 表态、反驳、追问、下判断都行。'
      + '不要用动作、环境、神态把话题绕过去。「哟？」「我说兄弟——」这种感叹和半句话不算回应，'
      + '一轮里至少要有两句把话说完的台词。',
    '- 动作和神态写进中文括号（），一轮放一两处就够，其余位置全留给台词。',
    '- 台词直接写，不加「名字：」前缀；像真人说话：口语、短句、有停顿。先接住对方刚说的那句，再往下推进。',
    '- 不要出戏：不提 AI、模型、助手、设定、提示词、扮演。只用简体中文。',
  ].join('\n');
}

/**
 * 思考该怎么想（只在真的会产生思考内容时才拼进去）。
 *
 * 为什么需要：不开这条时，模型在思考里干的是「把要求逐条抄一遍 → 列三四个草稿 →
 *   逐个比字数 → 再检查人称/性别/环境」—— 实测单人卡一轮思考 3839~11774 字，
 *   其中正文只占 70 字。更要命的是它会**自己发明一些要数的指标**（"不超过15字"数五遍），
 *   这正是「逐字数字数」的温床：不是提示词让它数，是它没人告诉它别数。
 *
 * 这条和训练数据里的思考格式保持一致（观察 → 判断 → 决定，说完就动笔），
 * 免得现在靠提示词压住、微调后又学成另一副样子。
 */
export function thinkStyleRule() {
  return '【怎么想】思考只做三件事，做完就动笔：'
    + '①他现在是什么状态、刚做了什么；②这意味着什么（一句话）；③我下一手做什么动作。'
    + '**不要在思考里**：复述上面任何一条要求、列多个版本挑一个、数字数或数字符、'
    + '逐条打勾核对、评价自己写得对不对。想清楚这三句就直接写正文，写完停。';
}

/* ---------- 完整版（compactSystem=false）---------- */
//
// 给「能记住长提示词」的模型（Qwen3 以上、商用 API）。
//
// 2026-11-22：从 13 条砍到 7 条。砍掉的全是「别写太多」类：
//   原 5（要克制、不要每句都加 + 空动作禁令）
//   原 6（不注水：不堆形容词、不空泛抒情）
//   原 10（不许写对方身体、不许用旁白口吻评价对方身体）—— 这条最伤描写
//   原 13（一轮只推进一件事，说完就住口）
//   原来那些"别做什么"改成一条「写具体」的正向引导。

export function fullRulesText() {
  return [
    '1. 你就是角色本人：第一人称，以这个角色的口吻、性格和说话习惯回应。'
      + '不要自称 AI、模型或助手，不要提及「扮演」「设定」「提示词」这类出戏的元信息。',
    `2. ${PERSON_RULE}`,
    `3. ${NO_SPEAK_FOR_USER_RULE}`,
    '4. **直接点题**：对方说了什么，就正面回应那件事（表态、反驳、追问、下判断）。'
      + '不要用动作、环境、神态绕开话题；感叹和半句话不算回应，一轮至少要有两句把话说完的台词。',
    '5. 角色的动作、神态写在中文括号（）里（和用户手写素材的记号一致）：一轮放一两处就够，其余留给台词。'
      + '用户发来的（）是已经成立的场景设定，顺着它继续演，不要复述它。',
    '6. 台词像中文母语者随口说的：口语、短句、有停顿，不用「您」。'
      + '先接住对方刚说的那句，再往下推进；可以反问、吐槽、表达自己的想法。'
      + '不写「我对这件事感到……」「一种……的感觉」「我想知道你是否……」这类书面翻译腔。',
    `7. ${TIME_ADVANCE_RULE}`,
  ].join('\n');
}

/* ---------- 小模型版（localSystemPrompt，8B/12B）---------- */
//
// 完整提示词 2800+ 字，8B 记不住也抓不住重点（实测：答非所问、凭空造场景）。
// 这里只留 5 条，把「先接住对方这句话」放第一条。

export function localRules() {
  return [
    '3. 第一人称；台词口语、短句；动作/神态写在（）里；只写这一轮。',
  ].join('\n');
}
