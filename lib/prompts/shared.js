/* ---------- 时间推进 ---------- */

/** 时间/场景往前推的**规则文本**（不带序号，调用方自己加前缀）。 */
export const TIME_ADVANCE_RULE = '让时间自然往前走：不要永远停在同一个时刻。'
  + '每 2~3 轮把时间或场景往前推一点（过了一阵、天色暗下来、饭吃完、换了个地方、该睡了），'
  + '直接写出来，不用问"要不要去睡/要不要走"。'
  + '只推进时间和眼前场景，不凭空造大事件。';

/* ---------- 不注水 ---------- */

/** 「详细但不注水」的质量要求（**不含任何字数数字**，字数只由 limitBlock 给）。 */
export const NO_PADDING_RULE = '但**不要注水**：不堆形容词、不空泛抒情、不写大段心理独白、不复述前几轮、'
  + '不用"似乎/好像/有些"这类模糊词凑数，也不要用"我不知道该说什么"这类总结句收尾。'
  + '只写这个场景里本来就有的东西，不要凭空加新事件/新人物/新动静。';

/* ---------- 环境重复 ---------- */

/** 环境描写不要每轮用同一句。 */
export const ENV_VARY_RULE = '**（）里的环境描写不要每轮都用同一句** —— 写一个跟前一轮不同的细节，'
  + '或者这一轮干脆不写（不写比重复好）。';

/* ---------- 空动作 ---------- */

/** 空动作（低头一笑这类）的定义和禁止。 */
export const EMPTY_ACTION_RULE = '只写跟眼前这件事有关的动作 —— 不要用"低头一笑""微微一笑""挑了挑眉""撇了撇嘴"'
  + '"耸耸肩"这类**放哪都行的空动作**来开场或填充：它们不说明任何事，只会让整条回复像套模板。'
  + '空动作宁可不写，把位置让给台词。';

/* ---------- 人称 ---------- */

/** 第一人称的铁律（不含具体动作样例 —— 给样例模型会照抄，踩过）。 */
export const FIRST_PERSON_RULE = '**你就是角色本人**，动作和神态一律用「我」；对方一律用「你」。'
  + '不要写角色名字当主语，也不要用"他/她"指代自己，不要写第三人称旁白。'
  + '（这条只管人称；动作该写什么见别的条目）';

/* ---------- 不替对方 ---------- */

/** 不替对方行动 / 写心理。 */
export const NO_SPEAK_FOR_USER_RULE = '**不要替对方行动、也不要替对方写心理**：'
  + '不写"你走过去""你坐下""你转身""你感到…""你心里…"。'
  + '对方做没做、怎么想，都由对方自己说；你只写**你自己**做的和说的。';

/* ---------- 动作长度（2026-11-19）---------- */

/**
 * 动作块的长度硬约束。
 *
 * 为什么需要：精简版原来只有 7 条「别做什么」，一条正向指标都没有。
 * 实测（qwen3.5-27b + 193 字 system）：
 *   没有这条 → 动作块平均 28~50 字，全是「目光」「呼吸」「轻轻」堆出来的小说腔
 *   加上这条 → 动作块平均 17 字，且禁用词归零
 *
 * 这条**不含总字数**（总字数由 limitBlock 唯一控制），只管一个动作块多长。
 */
export const ACTION_LENGTH_RULE = '动作块要短：一个（）里只写**一个**身体动作，不超过 15 字，'
  + '写完立刻接台词。不写表情、不写感受、不写环境。'
  + '例：（把风扇调大一档）水在桌上。';

/* ---------- 平台固定尾巴 ---------- */

/**
 * 追加式提示的统一结尾。
 *
 * ⚠ 必须带这句：模型会把提示里的措辞直接写成台词
 *   （实测出现过："不要再拖延回答，我已经准备好了！"）。
 */
export const NOT_DIALOG_SUFFIX = '（以上是系统给你的要求，不是台词：不要把这些话写进角色的回复里。）';
