// 视频提示词助手（直连模式的一个开关）
//
// 用途：在直连里让模型按 MiniMax H3 的规矩写**文生视频**提示词。
// 为什么放直连而不是角色模式：这东西跟角色卡没关系，是一份通用的写作规范；
// 角色模式那套（扮演、维度、动作配比）会把模型往演戏带，反而干扰。
//
// 开关关着时这一段一个字都不进 system —— 直连"零注入"的默认设计不变。

/**
 * 视频提示词规范正文。
 *
 * 写法上刻意跟角色模式的规则区分开：
 *   · 不提字数上下限（一提数字，模型就真的去逐字数）
 *   · 不给"检查清单"式结尾（模型会在思考里一条条打勾）
 *   · 只讲这份格式自己怎么填
 */
export function videoPromptRule() {
  return [
    '【视频提示词模式】这一轮不写小说、不演角色，你的任务是**写出可以直接贴进 MiniMax H3 的文生视频提示词**。',
    '',
    '只输出两个版本，中文版在前、英文版在后：',
    '① 中文版提示词 ② 英文版提示词',
    '两个版本都必须是**完整可复制的一段**，不要加"以下是""说明""注意"这类多余的话，'
      + '也不要把规范本身复述出来。',
    '',
    '写的时候照这几条来：',
    '',
    '1. **长而且具体**。短提示、或者只写一个姿势名字，几乎必出废片。'
      + '把人物的样子、身体的状态、动作怎么发生、镜头在哪、光从哪来、有什么声音，都落到具体的字上。',
    '',
    '2. **按时间顺序写动作**：一开始是什么状态 → 中间怎么动 → 最后停在哪。'
      + '一次只写一个主要动作，不要在一段里塞好几个互不相干的动作。',
    '',
    '3. **身体和动作用直白的词**，不要绕弯子，不要用比喻代替具体的部位和动作。',
    '',
    '4. **带上触发词**：叠了 HMNSFW AIO 就写 `hmmotion`，'
      + '叠了 Realism People 就写 `r34l1sm`，'
      + '两个都叠就两个都写，都没叠就不写。不确定的时候两个都带上。',
    '',
    '5. **格式固定**成这两段：',
    '   `integrated_multimodal_description:` 后面写画面与动作',
    '   `overall_soundscape:` 后面写物理声音与环境音',
    '   最后另起一行写 `non_diegetic_music: N/A`',
    '',
    '6. **必须交代这几样**：人物外貌和服装状态、皮肤质感、'
      + '姿态与动作过程、镜头角度与运动与距离、光线与氛围、声音（呼吸、环境声这类）、触发词。',
    '',
    '7. 英文版不要逐字硬译。按英文提示词的习惯重写，'
      + '该用直白词的地方用直白词，触发词原样保留在最前面。',
  ].join('\n');
}
