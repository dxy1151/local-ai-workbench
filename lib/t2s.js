const T2S_RE = new RegExp('[' + Object.keys(T2S).join('') + ']', 'g');

/** 把繁体字转成简体。没有繁体字时原样返回（零开销）。 */
export function toSimplified(text) {
  const s = String(text || '');
  if (!T2S_RE.test(s)) return s;
  T2S_RE.lastIndex = 0;
  return s.replace(T2S_RE, (ch) => T2S[ch] || ch);
}

/**
 * 删掉比喻分句。
 *
 * 为什么用后处理而不是提示词：v16 在低温度下仍会生成「像是含着一颗温热的
 * 小石头」「跟冰糖苹果似的」这类比喻，提示词写「不要打比方」压了三次都没压住
 * （反而因为反例里放了具体物名，模型照着那些词造）。
 *
 * 策略：只删「像…，」「如同…，」「跟…似的」这种完整分句，括号里的动作不动。
 */
export function stripMetaphor(text) {
  const s = String(text || '');
  if (!/(?:像是?|如同|仿佛|宛如)|跟[^（()），。]{2,15}似的/.test(s)) return s;
  // 按行处理：每行是一个「（动作）台词」单元
  const lines = s.split('\n');
  const out = [];
  for (const line of lines) {
    // 把「（...）」动作括号抽出来保护，只处理括号外的文字
    const parts = line.split(/(（[^）]*）|\([^)]*\))/);
    const kept = parts.map((seg) => {
      if (/^[（(]/.test(seg)) return seg;   // 括号原样保留
      // 括号外：比喻句整个删掉（不是只删「像」字，要删到句末）
      if (!/(?:像是?|如同|仿佛|宛如)|跟[^，。]{2,15}似的/.test(seg)) return seg;
      // 按句号切，含比喻的句子整句删
      const sents = seg.split(/(?<=[。！？～])/);
      const keptSents = sents.filter((x) => !/(?:像是?|如同|仿佛|宛如)|跟[^，。]{2,15}似的/.test(x));
      return keptSents.join('');
    }).join('');
    out.push(kept);
  }
  const result = out
    .join('\n')
    .replace(/[，。；]{2,}/g, '。')
    .replace(/）[，。；]{2,}/g, '）。')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  // 兜底：如果删完只剩括号没有台词（中文不到 8 字），说明删过头了，返回原文。
  // 宁可留着比喻，也不要给用户一个空回复。
  const spoken = result.replace(/（[^）]*）|[^\u4e00-\u9fff，。！？～…]/g, '');
  if (spoken.length < 8 && s.length > 20) return s;
  return result;
}
